CREATE DATABASE IF NOT EXISTS mecanica;
USE mecanica;

-- 1. CLIENTE
CREATE TABLE IF NOT EXISTS CLIENTE (
    ID_cliente INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CPF VARCHAR(14) UNIQUE NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(100),
    ENDEREÇO VARCHAR(40),
    status_cliente ENUM('ATIVO', 'DESATIVADO') DEFAULT 'ATIVO',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. VEICULOS
CREATE TABLE IF NOT EXISTS VEICULOS (
    ID_VEICULOS INT AUTO_INCREMENT PRIMARY KEY,
    PLACA CHAR(8) NOT NULL UNIQUE,
    tipo ENUM('CARRO', 'CAMINHÃO', 'MOTO') DEFAULT 'CARRO',
    COR CHAR(20),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    QUILOMETRAGEM FLOAT
);

-- 3. MARCA
CREATE TABLE IF NOT EXISTS MARCA (
    ID_MARCA INT AUTO_INCREMENT PRIMARY KEY,
    ANO YEAR,
    PAIS VARCHAR(30),
    STATUS_MARCA ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    CONTRATO VARCHAR(50),
    veiculos VARCHAR(255),
    itens VARCHAR(255),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. MODELO
CREATE TABLE IF NOT EXISTS MODELO (
    ID_MODELO INT AUTO_INCREMENT PRIMARY KEY,
    COR VARCHAR(20),
    ANO_MODELO YEAR,
    VALOR_MODELO DECIMAL(10, 2) NOT NULL,
    CATEGORIA ENUM('SUV', 'HATCH', 'SEDAN', 'ESPORTIVA'),
    NOME_MODELO VARCHAR(60),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. FUNCIONARIO
CREATE TABLE IF NOT EXISTS FUNCIONARIO (
    ID_funcionario INT AUTO_INCREMENT PRIMARY KEY,
    nome_de_funcionario VARCHAR(100) NOT NULL,
    cpf_do_funcionario VARCHAR(14) UNIQUE NOT NULL,
    cargo_funcionario VARCHAR(50) NOT NULL,
    Salario DECIMAL(10,2) NOT NULL,
    telefone VARCHAR(20),
    status_funcionario ENUM('ATIVO', 'INATIVO') DEFAULT 'ATIVO',
    email VARCHAR(100) UNIQUE,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. SERVICOS
CREATE TABLE IF NOT EXISTS SERVICOS (
    ID_SERVICOS INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_SERVICO VARCHAR(60) NOT NULL,
    DESCRICAO VARCHAR(250) NOT NULL,
    PRECO_SERVICO DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    DATA_TERMINO DATETIME NOT NULL,
    STATUS ENUM('EM ANDAMENTO', 'PENDENTE', 'CONCLUIDO') DEFAULT 'PENDENTE',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 7. PECAS
CREATE TABLE IF NOT EXISTS PECAS (
    ID_PECAS INT AUTO_INCREMENT PRIMARY KEY,
    NOME_PECA VARCHAR(60) NOT NULL,
    LOCAL VARCHAR(50),
    VALOR_PECA DECIMAL(10, 2) NOT NULL,
    TAMANHO VARCHAR(14) NOT NULL,
    VALIDADE DATE NOT NULL,
    STATUS_PECA ENUM('DISPONIVEL', 'INDISPONIVEL') DEFAULT 'DISPONIVEL',
    QNTDE_CADASTRO INT,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. ORDENS_SERVICOS
CREATE TABLE IF NOT EXISTS ORDENS_SERVICOS (
    ID_ORDEM INT AUTO_INCREMENT PRIMARY KEY, 
    PRIORIDADE ENUM('URGENTE', 'SIMPLES') NOT NULL DEFAULT 'SIMPLES',
    PRAZO_FINAL DATE NOT NULL,
    RANKING_ORDEM VARCHAR(40) NOT NULL,
    DATA_EMISSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    TIPO_CASO VARCHAR(200) NOT NULL,
    STATUS_SERVICO ENUM('EM ANDAMENTO', 'PENDENTE', 'CONCLUIDO') DEFAULT 'PENDENTE',
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. FORNECEDORES
CREATE TABLE IF NOT EXISTS FORNECEDORES (
    ID_FORNECEDORES INT AUTO_INCREMENT PRIMARY KEY,
    razao_social VARCHAR(60) NOT NULL,
    CNPJ CHAR(20) UNIQUE NOT NULL,
    telefone_contato VARCHAR(14) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    incricao_estadual CHAR(10),
    segmento_fornecedor VARCHAR(50) NOT NULL,
    endereco_fornecedor VARCHAR(100) NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. PAGAMENTO
CREATE TABLE IF NOT EXISTS PAGAMENTO (
    ID_PAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    FORMA_PAGAMENTO ENUM('DINHEIRO', 'PIX', 'CARTÃO CRÉDITO', 'CARTÃO DÉBITO', 'BOLETO') NOT NULL,
    VALOR_PAGO DECIMAL(10, 2) NOT NULL,
    STATUS_PAGAMENTO ENUM('PENDENTE', 'APROVADO', 'CANCELADO') DEFAULT 'PENDENTE',
    DATA_PAGAMENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

